using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Archz.Architecture.Tests;

internal sealed record BackendSourceFile(string AssemblyName, string ProjectDirectory, string Path, CompilationUnitSyntax Root)
{
    public IEnumerable<TypeDeclarationSyntax> TopLevelClasses =>
        Root.DescendantNodes()
            .OfType<TypeDeclarationSyntax>()
            .Where(type => type.Parent is CompilationUnitSyntax or BaseNamespaceDeclarationSyntax)
            .Where(type => type is ClassDeclarationSyntax or RecordDeclarationSyntax &&
                !type.IsKind(SyntaxKind.RecordStructDeclaration));

    public bool IsGenerated => Root.GetLeadingTrivia().Any(trivia =>
        (trivia.Kind() is SyntaxKind.SingleLineCommentTrivia or SyntaxKind.MultiLineCommentTrivia) &&
        trivia.ToString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase));

    public static IReadOnlyList<BackendSourceFile> LoadCompilerInputs()
    {
        using var stream = typeof(BackendSourceFile).Assembly
            .GetManifestResourceStream("ArchitectureCompilerInputs")
            ?? throw new InvalidOperationException("Build the architecture test project to collect the backend compiler inputs.");
        using var reader = new StreamReader(stream);
        List<BackendSourceFile> sources = [];
        while (reader.ReadLine() is { } line)
        {
            var columns = line.Split('|', 4);
            var symbols = columns[1].Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
            var path = columns[3];
            var options = CSharpParseOptions.Default.WithPreprocessorSymbols(symbols);
            var root = CSharpSyntaxTree.ParseText(File.ReadAllText(path), options, path).GetCompilationUnitRoot();
            sources.Add(new BackendSourceFile(columns[0], columns[2], path, root));
        }

        return sources;
    }

    public static string MetadataFullName(TypeDeclarationSyntax type)
    {
        var arity = type.TypeParameterList?.Parameters.Count ?? 0;
        var name = arity == 0 ? type.Identifier.ValueText : $"{type.Identifier.ValueText}`{arity}";
        return string.Join(".", type.Ancestors()
            .OfType<BaseNamespaceDeclarationSyntax>()
            .Reverse()
            .Select(declaration => string.Concat(declaration.Name.DescendantTokens().Select(token => token.ValueText)))
            .Append(name));
    }
}
